const vscode = require('vscode')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')

const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
async function until(check, label, timeout = 40000) {
  const start = Date.now()
  while (Date.now() - start < timeout) {
    const result = await check()
    if (result) return result
    await delay(150)
  }
  throw new Error('Timed out: ' + label)
}

exports.run = async () => {
  const results = []
  let api
  const progress = setInterval(() => { if (api) fs.writeFile(process.env.BADGER_TEST_RESULT, JSON.stringify({ running: true, results, status: api.getStatus() }, null, 2)).catch(() => {}) }, 1000)
  try {
    const extension = vscode.extensions.getExtension('badger.badger-simulator')
    assert.ok(extension)
    api = await extension.activate()
    await vscode.commands.executeCommand('badger.reset')
    await until(() => api.getStatus().runtime.mode === 'home' && api.getStatus().runtime.state === 'Badge home' && api.getStatus().runtime.frames > 0, 'home without an open app')
    assert.equal(api.getStatus().root, undefined)
    results.push('Reset boots the badge home menu without an open app')
    const app = path.join(process.env.BADGER_TEST_WORKSPACE, 'my-app')
    await vscode.commands.executeCommand('badger.openProject', vscode.Uri.file(app))
    await vscode.workspace.getConfiguration('badger').update('livePreview', true, vscode.ConfigurationTarget.Workspace)
    await until(() => api.getStatus().runtime.mode === 'app' && api.getStatus().runtime.state === 'Running' && api.getStatus().runtime.frames > 0, 'first app MicroPython frame')
    const sourceEditor = await until(() => vscode.window.visibleTextEditors.find(editor => editor.document.fileName.endsWith('__init__.py')), 'native source editor stays visible beside emulator')
    assert.equal(sourceEditor.viewColumn, vscode.ViewColumn.One)
    results.push('Native Python editor on the left and MicroPython frames on the right')
    await until(() => api.getStatus().runtime.model === 'ready', '3D model in native webview')
    results.push('3D model renders in the VS Code webview')
    const document = await vscode.workspace.openTextDocument(vscode.Uri.file(path.join(app, '__init__.py')))
    const edit = new vscode.WorkspaceEdit()
    edit.insert(document.uri, new vscode.Position(0, 0), 'print("BADGER_UNSAVED_CHANGE")\n')
    await vscode.workspace.applyEdit(edit)
    assert.equal(document.isDirty, true)
    await until(() => api.getStatus().runtime.log?.includes('BADGER_UNSAVED_CHANGE'), 'unsaved native edit reruns emulator')
    results.push('Unsaved changes from VS Code restart the emulator')
    const unsavedSource = document.getText()
    await vscode.commands.executeCommand('badger.reset')
    await until(() => api.getStatus().runtime.mode === 'home' && api.getStatus().runtime.state === 'Badge home' && api.getStatus().runtime.frames > 0, 'reset from app to badge home')
    assert.equal(document.isDirty, true)
    assert.equal(document.getText(), unsavedSource)
    const hanging = new vscode.WorkspaceEdit()
    hanging.replace(document.uri, new vscode.Range(document.positionAt(0), document.positionAt(document.getText().length)), 'while True:\n    pass\n')
    await vscode.workspace.applyEdit(hanging)
    await delay(1000)
    assert.equal(api.getStatus().runtime.mode, 'home')
    await vscode.commands.executeCommand('badger.run')
    await until(() => api.getStatus().runtime.mode === 'app' && api.getStatus().runtime.state === 'Running', 'non-yielding app starts')
    await vscode.commands.executeCommand('badger.reset')
    await until(() => api.getStatus().runtime.mode === 'home' && api.getStatus().runtime.state === 'Badge home' && api.getStatus().runtime.frames > 0, 'reset recovers from non-yielding app')
    results.push('Reset recovers from a non-yielding app and preserves unsaved files')
    const restore = new vscode.WorkspaceEdit()
    restore.replace(document.uri, new vscode.Range(document.positionAt(0), document.positionAt(document.getText().length)), unsavedSource)
    await vscode.workspace.applyEdit(restore)
    await vscode.commands.executeCommand('badger.run')
    await until(() => api.getStatus().runtime.mode === 'app' && api.getStatus().runtime.state === 'Running' && api.getStatus().runtime.frames > 0, 'Run returns to workspace source')
    results.push('Run resumes the workspace app after Reset')
    await document.save()
    const disk = path.join(process.env.BADGER_TEST_WORKSPACE, 'BADGER')
    await fs.mkdir(path.join(disk, 'apps'), { recursive: true })
    await vscode.commands.executeCommand('badger.connect', vscode.Uri.file(disk))
    await vscode.commands.executeCommand('badger.upload')
    assert.equal(await fs.readFile(path.join(disk, 'apps/my-app/__init__.py'), 'utf8'), document.getText())
    results.push('Native upload command writes and verifies a mock BADGER volume')
    await fs.writeFile(path.join(app, 'helper.py'), 'value = 42\n')
    await vscode.commands.executeCommand('badger.upload')
    assert.equal(await fs.readFile(path.join(disk, 'apps/my-app/helper.py'), 'utf8'), 'value = 42\n')
    await fs.unlink(path.join(app, 'helper.py'))
    await vscode.commands.executeCommand('badger.upload')
    await assert.rejects(fs.access(path.join(disk, 'apps/my-app/helper.py')))
    results.push('Native upload applies new files and tracked deletions')
    await fs.writeFile(path.join(disk, 'apps/my-app/__init__.py'), 'external badge edit')
    const conflict = new vscode.WorkspaceEdit()
    conflict.insert(document.uri, new vscode.Position(0, 0), 'print("local update")\n')
    await vscode.workspace.applyEdit(conflict)
    await document.save()
    await vscode.commands.executeCommand('badger.upload')
    assert.match(api.getStatus().error, /changed on the badge/)
    assert.equal(await fs.readFile(path.join(disk, 'apps/my-app/__init__.py'), 'utf8'), 'external badge edit')
    results.push('Native upload blocks overwriting external badge edits')
    await vscode.commands.executeCommand('badger.disconnect')
    assert.equal(api.getStatus().diskRoot, undefined)
    await vscode.commands.executeCommand('badger.stop')
    await until(() => api.getStatus().runtime.state === 'Stopped', 'stop')
    results.push('Stop terminates the runtime')
    await fs.writeFile(process.env.BADGER_TEST_RESULT, JSON.stringify({ passed: true, results, status: api.getStatus() }, null, 2))
  } catch (error) {
    await fs.writeFile(process.env.BADGER_TEST_RESULT, JSON.stringify({ passed: false, results, error: error.stack, status: api?.getStatus() }, null, 2))
    throw error
  } finally {
    clearInterval(progress)
    await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor')
  }
}
